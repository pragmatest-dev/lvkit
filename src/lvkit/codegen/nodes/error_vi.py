"""Code generator for the vi.lib error VIs.

Error Cluster From Error Code raises ``LabVIEWError``; the others generate
nothing at their call (see ``codegen/error_wires.py``).
"""

from __future__ import annotations

import ast

from lvkit.graph.models import VINode
from lvkit.parser.constants import VI_NAME_ERROR_CLUSTER_FROM_ERROR_CODE
from lvkit.vilib_resolver import get_resolver

from ..ast_utils import parse_expr
from ..context import CodeGenContext
from ..error_codes import describe_error_code
from ..errors_module import LABVIEW_ERROR_NAME
from ..fragment import CodeFragment

_ERROR_CODE_TERMINALS = {
    "code": "error_code_0",
    "message": "error_message",
    "is_warning": "is_warning_false",
}


def generate(node: VINode, ctx: CodeGenContext) -> CodeFragment:
    """Generate the call of a vi.lib error VI.

    Error Cluster From Error Code raises ``LabVIEWError`` when the code is not
    zero. The other error VIs (Clear Errors, Merge Errors, the error handlers)
    are generated by the nodes that wrap the code that raises the error they
    handle, so their call generates nothing.

    A constant code is known here, so its description is written into the module
    as the message (the wired message wins when there is one).
    """
    resolver = get_resolver()
    catalog_path = ctx.graph.catalog_path(node) if ctx.graph else node.qualified_path
    if (
        resolver.catalog_file_name(catalog_path)
        != VI_NAME_ERROR_CLUSTER_FROM_ERROR_CODE
    ):
        return CodeFragment.empty()
    entry = resolver.resolve_recorded(catalog_path)
    if entry is None:
        return CodeFragment.empty()
    index_of = {t.python_param: t.index for t in entry.terminals if t.direction == "in"}

    def wired(role: str) -> str | None:
        index = index_of.get(_ERROR_CODE_TERMINALS[role])
        for term in ctx.enriched_terminals(node):
            if term.direction == "input" and term.index == index:
                return ctx.wired_input(term.id, node)
        return None

    code = wired("code")
    if code is None:
        return CodeFragment.empty()
    try:
        constant = ast.literal_eval(code)
    except (ValueError, SyntaxError):
        constant = None
    if constant == 0 and isinstance(constant, int):
        return CodeFragment.empty()

    warning = wired("is_warning")
    if warning == "True":
        return CodeFragment.empty()

    message = wired("message")
    if message in ("''", '""'):
        message = None
    description = describe_error_code(constant) if isinstance(constant, int) else None
    if description is not None:
        message = f"{message} or {description!r}" if message else repr(description)
    raise_stmt: ast.stmt = ast.Raise(
        exc=ast.Call(
            func=ast.Name(id=LABVIEW_ERROR_NAME, ctx=ast.Load()),
            args=[],
            keywords=[
                ast.keyword(arg="code", value=parse_expr(code)),
                ast.keyword(arg="message", value=parse_expr(message or "''")),
            ],
        ),
        cause=None,
    )
    ctx.import_labview_error()
    condition = None if isinstance(constant, int) else f"{code} != 0"
    if warning not in (None, "False"):
        condition = f"{condition or 'True'} and not {warning}"
    if condition is None:
        return CodeFragment(statements=[raise_stmt])
    return CodeFragment(
        statements=[ast.If(test=parse_expr(condition), body=[raise_stmt], orelse=[])]
    )
